def load_panel():
    if os.path.exists(PANEL):
        return pd.read_csv(PANEL, index_col=0, parse_dates=True)
    return pd.DataFrame()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--sleep", type=float, default=0.3)
    args = ap.parse_args()

    panel = load_panel()
    have = set(panel.columns)
    # 去重清单内重复代码
    seen, uniq = set(), []
    for c, n in TARGETS:
        if c in seen:
            continue
        seen.add(c); uniq.append((c, n))
    todo = [(c, n) for c, n in uniq if c.lstrip("0") + "_HK" not in have]

    if args.status:
        print(f"面板 {panel.shape[0]} 行 x {panel.shape[1]} 列; 清单去重后 {len(uniq)}, 待抓 {len(todo)}")
        return

    print(f"现有港股 {panel.shape[1]} 列 | 待抓 {len(todo)} 个", flush=True)
    ok, fail = {}, []
    for i, (code, name) in enumerate(todo, 1):
        sym, tag = "hk" + code, code.lstrip("0") + "_HK"
        try:
            s = fetch_full(sym, "hk", name, fq="hfq", start_year=1990)
            if s is None or len(s) < 10:
                raise RuntimeError("数据过少")
            s.name = tag
            ok[tag] = s
            s.to_csv(os.path.join(RAW_DIR, f"{tag}.csv"), header=["close"])
            print(f"{i:3d}/{len(todo)} {tag:10s} {name:12s} {len(s):5d}周 "
                  f"{s.index[0].date()}~{s.index[-1].date()}", flush=True)
        except Exception as e:
            print(f"{i:3d}/{len(todo)} {tag:10s} {name:12s} ERR {str(e)[:50]}", flush=True)
            fail.append(tag)
        time.sleep(args.sleep)
        # 每 40 个存盘一次
        if len(ok) > 0 and len(ok) % 40 == 0:
            new = pd.DataFrame(ok).sort_index()
            panel = pd.concat([panel, new], axis=1, sort=True)
            panel = panel.loc[:, ~panel.columns.duplicated()]
            panel = panel[~panel.index.duplicated(keep="last")].sort_index()
            panel.to_csv(PANEL)
            print(f"  --- 阶段存盘: 港股面板 {panel.shape[1]} 列 ---", flush=True)
            ok = {}

    if ok:
        new = pd.DataFrame(ok).sort_index()
        panel = pd.concat([panel, new], axis=1, sort=True)
        panel = panel.loc[:, ~panel.columns.duplicated()]
        panel = panel[~panel.index.duplicated(keep="last")].sort_index()
        panel.to_csv(PANEL)
    print(f"\n成功 {len(uniq)-len(fail)} / 失败 {len(fail)}")
    print(f"港股面板: {panel.shape[0]} 行 x {panel.shape[1]} 列")
    if fail:
        print("失败:", ", ".join(fail[:40]))


if __name__ == "__main__":
    main()
